type DeepLeafPaths<T, P extends string = ""> = T extends string
 ? P extends ""
 ? never
 : P
 : {
 [K in keyof T]: K extends string
 ? DeepLeafPaths<T[K], P extends "" ? K : `${P}.${K}`>
 : never;
 }[keyof T];

